<script lang="ts">
  import '$lib/styles/base.css';
  import { onMount } from 'svelte';

  onMount(() => {
    if ('serviceWorker' in navigator) {
      navigator.serviceWorker
        .register('/service-worker.js')
        .catch((error) => console.warn('Service worker registration failed', error));
    }
  });
</script>

<slot />
